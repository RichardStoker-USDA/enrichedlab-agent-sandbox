args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2L) stop("Usage: Rscript analysis.R INPUT_CSV OUTPUT_DIRECTORY")
input <- args[[1L]]
output <- args[[2L]]
if (dir.exists(output) && length(list.files(output, all.files = TRUE, no.. = TRUE))) {
  stop("Output directory must be empty; preserve each earlier attempt")
}
dir.create(output, recursive = TRUE, showWarnings = FALSE)
x <- read.csv(input, check.names = FALSE, stringsAsFactors = FALSE)
stopifnot(identical(names(x), c("len", "supp", "dose")), nrow(x) > 0L,
          is.numeric(x$len), is.numeric(x$dose), !anyNA(x),
          all(is.finite(x$len)), all(is.finite(x$dose)),
          all(x$len >= 0), all(x$dose > 0), all(nzchar(x$supp)))
x$supp <- factor(x$supp, levels = sort(unique(x$supp)))
groups <- split(x, interaction(x$supp, x$dose, drop = TRUE, lex.order = TRUE))
summary <- do.call(rbind, lapply(groups, function(g) data.frame(
  supplement = as.character(g$supp[[1L]]), dose = g$dose[[1L]],
  n = nrow(g), mean = mean(g$len), median = median(g$len),
  standard_deviation = if (nrow(g) > 1L) sd(g$len) else NA_real_
)))
rownames(summary) <- NULL
write.csv(summary, file.path(output, "summary.csv"), row.names = FALSE, na = "")
write.csv(data.frame(check = c("required_columns", "complete_records", "finite_measurements", "positive_dose"),
                     result = rep("passed", 4L)),
          file.path(output, "data_checks.csv"), row.names = FALSE)
draw <- function() {
  par(mar = c(5, 4.5, 3.5, 1), family = "sans", las = 1)
  labels <- vapply(groups, function(g) paste(as.character(g$supp[[1L]]), g$dose[[1L]], sep = " / "), "")
  yrange <- range(x$len)
  plot(NA, xlim = c(0.5, length(groups) + 0.5), ylim = extendrange(yrange, f = 0.1),
       xaxt = "n", xlab = "Supplement / vitamin C dose (mg/day)", ylab = "Tooth length",
       main = "Original observations and group means", bty = "l", col.axis = "#53647A")
  abline(h = axTicks(2), col = "#E4E9EF", lwd = 0.6)
  palette <- colorRampPalette(c("#022851", "#FFBF00"))(nlevels(x$supp))
  for (i in seq_along(groups)) {
    g <- groups[[i]]
    offsets <- if (nrow(g) > 1L) seq(-0.15, 0.15, length.out = nrow(g)) else 0
    color <- palette[as.integer(g$supp[[1L]])]
    points(i + offsets, g$len, pch = 21, cex = 0.85, col = "#022851", bg = color)
    segments(i - 0.22, mean(g$len), i + 0.22, mean(g$len), lwd = 2, col = "#022851")
  }
  axis(1, at = seq_along(groups), labels = labels, cex.axis = 0.8)
  mtext("Public reference data; descriptive comparison", side = 3, line = 0.3, cex = 0.75, col = "#53647A")
}
pdf(file.path(output, "figure.pdf"), width = 8.5, height = 5.5, useDingbats = FALSE)
