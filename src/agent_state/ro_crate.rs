//! Exporting a run as an RO-Crate.
use super::*;

/// The RO-Crate specification, its JSON-LD context and the profile the export declares (RO-Crate 1.3 of June 2026;
/// Process Run Crate 0.6, which builds on it).
pub(super) const RO_CRATE_SPEC: &str = "https://w3id.org/ro/crate/1.3";

pub(super) const RO_CRATE_CONTEXT: &str = "https://w3id.org/ro/crate/1.3/context";

pub(super) const PROCESS_RUN_CRATE: &str = "https://w3id.org/ro/wfrun/process/0.6";

/// The namespace of the export's own terms. RO-Crate 1.3 needs every key in the context and an ad hoc term defined in the
/// crate; a UUID URN names them without claiming a domain or a w3id namespace not yet registered. A vocabulary published
/// later can declare these IRIs equivalent to its own.
pub(super) const STATE_TERMS: &str = "urn:uuid:516305d7-526a-4182-91ff-25c8d6195928#";

/// Each key the export adds, with its meaning, as the crate defines it.
pub(super) const STATE_TERM_DEFINITIONS: [(&str, &str); 13] = [
    (
        "recordedByEvent",
        "The events that recorded the file in the run. Each registers the file's bytes under a role the caller named; it \
         says nothing of how or by what the file was made.",
    ),
    (
        "includedInPackage",
        "Whether the file's bytes are in this package. A restricted file left out keeps its digest and size.",
    ),
    (
        "sensitivity",
        "The file's data class in the run: standard, restricted, or mixed when the run linked it both ways.",
    ),
    (
        "sequence",
        "The event's position in the state store's event log, which increases with every event recorded.",
    ),
    (
        "epoch",
        "The run's context epoch when the event was recorded.",
    ),
    ("kind", "The event's kind, a fixed dotted name."),
    (
        "actor",
        "Who recorded the event, as the state store names them.",
    ),
    (
        "authority",
        "The authority the event was recorded under: machine, model or operator.",
    ),
    (
        "payload",
        "The event's payload as recorded, present only when the export includes payloads.",
    ),
    ("payloadSha256", "The SHA-256 of the event's payload."),
    (
        "previousEventHash",
        "The hash of the run's previous event; empty for the run's first event.",
    ),
    ("eventHash", "This event's hash in the run's hash chain."),
    (
        "contextEpoch",
        "The run's context epoch when it was exported.",
    ),
];

/// The JSON-LD context: RO-Crate 1.3's, PROV-O for events and the times they started, and every key the export adds
/// mapped into `STATE_TERMS` (a payload kept as a JSON literal). The state store records custody: who registered which
/// bytes under which role, not what made them, so no file is said to be generated by an event or to be a run's result.
pub(super) fn export_context() -> Value {
    let mut local = serde_json::Map::new();
    local.insert("prov".into(), json!("http://www.w3.org/ns/prov#"));
    local.insert(
        "startedAtTime".into(),
        json!({"@id": "http://www.w3.org/ns/prov#startedAtTime",
            "@type": "http://www.w3.org/2001/XMLSchema#dateTime"}),
    );
    for (term, _) in STATE_TERM_DEFINITIONS {
        let id = format!("{STATE_TERMS}{term}");
        let definition = if term == "payload" {
            json!({"@id": id, "@type": "@json"})
        } else {
            json!({"@id": id})
        };
        local.insert(term.into(), definition);
    }
    json!([RO_CRATE_CONTEXT, local])
}

/// The crate's definition of each key the export adds: an `rdf:Property` with its name and meaning, as RO-Crate 1.3
/// asks of ad hoc terms.
pub(super) fn term_definitions() -> Vec<Value> {
    STATE_TERM_DEFINITIONS
        .iter()
        .map(|(term, meaning)| {
            json!({"@id": format!("{STATE_TERMS}{term}"), "@type": "rdf:Property", "name": term,
                "description": meaning, "rdfs:label": term, "rdfs:comment": meaning})
        })
        .collect()
}

/// One value as itself, several as a list (RO-Crate's compacted form).
pub(super) fn one_or_list(values: BTreeSet<String>) -> Value {
    if values.len() == 1 {
        json!(values.into_iter().next())
    } else {
        json!(values)
    }
}

pub fn export_run(
    config: &RuntimeConfig,
    run_id: &str,
    output_dir: &Path,
    include_restricted: bool,
    include_event_payloads: bool,
) -> Result<StateExportReceipt> {
    validate_identifier(run_id, "run id")?;
    if !output_dir.is_absolute() {
        bail!("state export output must be an absolute path");
    }
    if output_dir.exists() {
        bail!("state export output already exists");
    }
    let parent = output_dir
        .parent()
        .context("state export output has no parent directory")?;
    let parent_metadata = fs::symlink_metadata(parent)
        .with_context(|| format!("state export parent does not exist: {}", parent.display()))?;
    if parent_metadata.file_type().is_symlink() || !parent_metadata.is_dir() {
        bail!("state export parent must be a regular directory, not a symlink");
    }
    let output_name = output_dir
        .file_name()
        .and_then(|value| value.to_str())
        .context("state export output needs a UTF-8 directory name")?;
    let pending = parent.join(format!(".{output_name}.{}.pending", Uuid::new_v4()));
    create_private_dir(&pending)?;
    let result = (|| {
        let run = load_run(config, run_id)?;
        let events = trace(config, run_id)?;
        let artifact_links = artifacts_for_run(config, run_id)?;
        create_private_dir(&pending.join("artifacts"))?;
        let artifact_root = pending.join("artifacts/sha256");
        create_private_dir(&artifact_root)?;
        let mut copied = BTreeSet::new();
        let mut omitted = BTreeSet::new();
        let mut artifact_index: BTreeMap<String, ExportArtifactAggregate> = BTreeMap::new();
        for link in &artifact_links {
            let restricted = link.artifact.sensitivity == ArtifactSensitivity::Restricted;
            let indexed = artifact_index
                .entry(link.artifact.sha256.clone())
                .or_insert_with(|| ExportArtifactAggregate {
                    artifact: link.artifact.clone(),
                    has_standard_link: false,
                    has_restricted_link: false,
                    labels: BTreeSet::new(),
                    roles: BTreeSet::new(),
                    event_ids: BTreeSet::new(),
                });
            indexed.has_standard_link |= !restricted;
            indexed.has_restricted_link |= restricted;
            indexed.labels.insert(link.artifact.label.clone());
            indexed.roles.insert(link.artifact.role.clone());
            indexed.event_ids.insert(link.event_id.clone());
        }
        let mut artifact_entities = Vec::new();
        for indexed in artifact_index.into_values() {
            let artifact = indexed.artifact;
            let has_standard = indexed.has_standard_link;
            let has_restricted = indexed.has_restricted_link;
            let included = has_standard || include_restricted;
            let package_path = format!("artifacts/sha256/{}", artifact.sha256);
            if included {
                let source = config
                    .agent_state_artifacts_dir()
                    .join(&artifact.relative_path);
                copy_private_atomic(&source, &pending.join(&package_path), &artifact.sha256)?;
                copied.insert(artifact.sha256.clone());
            } else if has_restricted {
                omitted.insert(artifact.sha256.clone());
            }
            let sensitivity = match (has_standard, has_restricted) {
                (true, true) => "mixed",
                (true, false) => "standard",
                (false, true) => "restricted",
                (false, false) => unreachable!("artifact index has at least one link"),
            };
            // A file deliberately left out is a contextual entity (`#...`), not a path or an external URI: RO-Crate
            // 1.3's form for a file the package does not hold.
            artifact_entities.push(json!({
                    "@id": if included { format!("artifacts/sha256/{}", artifact.sha256) } else { format!("#artifact-sha256-{}", artifact.sha256) },
                    "@type": "File",
                    "sha256": artifact.sha256,
                    "contentSize": artifact.size,
                    "encodingFormat": artifact.media_type,
                    "name": one_or_list(indexed.labels),
                    "additionalType": one_or_list(indexed.roles),
                    "sensitivity": sensitivity,
                    "includedInPackage": included,
                    "recordedByEvent": indexed.event_ids.into_iter().map(|event_id| json!({"@id": format!("#event-{event_id}")})).collect::<Vec<_>>()
                }));
        }
        // A payload left out is absent, not null: `payload` is the payload as recorded.
        let event_nodes = events
            .iter()
            .map(|event| {
                let mut node = json!({
                    "@id": format!("#event-{}", event.event_id),
                    "@type": "prov:Activity",
                    "name": format!("{} (event {})", event.kind, event.sequence),
                    "sequence": event.sequence,
                    "epoch": event.epoch,
                    "kind": event.kind,
                    "actor": event.actor,
                    "authority": event.authority,
                    "startedAtTime": event.occurred_at,
                    "payloadSha256": event.payload_sha256,
                    "previousEventHash": event.previous_hash,
                    "eventHash": event.hash
                });
                if include_event_payloads {
                    node["payload"] = event.payload.clone();
                }
                node
            })
            .collect::<Vec<_>>();
        // RO-Crate 1.3 with the Process Run Crate 0.6 profile: the run is one CreateAction whose instrument is the
        // runtime that recorded it and whose object is the state-view profile it read; a profile is declared on the
        // root, and the descriptor names only the specification. The run record keeps no runtime version, so the run's
        // instrument names none; the export is a second CreateAction whose instrument is this program at its version.
        // The run names no `result`: a file's role is the registering caller's word, not recorded production, so the
        // files are the root's parts with their roles and the events that recorded them.
        let action_id = format!("#run-{run_id}");
        let sealed = run.status == "sealed";
        let mut action = json!({
            "@id": action_id,
            "@type": ["CreateAction", "prov:Activity"],
            "name": run_id,
            "agent": {"@id": format!("#agent-{}", run.subject)},
            "actionStatus": {"@id": if sealed { "http://schema.org/CompletedActionStatus" } else { "http://schema.org/ActiveActionStatus" }},
            "startTime": run.created_at,
            "instrument": {"@id": "#runtime"},
            "object": {"@id": "#profile"},
            "contextEpoch": run.epoch
        });
        if sealed {
            action["endTime"] = json!(run.updated_at);
        }
        let exported_at = now()?;
        let mut mentions = vec![json!({"@id": action_id}), json!({"@id": "#export"})];
        mentions.extend(event_nodes.iter().map(|event| json!({"@id": event["@id"]})));
        let mut graph = vec![
            json!({
                "@id": "ro-crate-metadata.json",
                "@type": "CreativeWork",
                "about": {"@id": "./"},
                "conformsTo": {"@id": RO_CRATE_SPEC}
            }),
            json!({
                "@id": "./",
                "@type": "Dataset",
                "name": format!("EnrichedLab agent state run {run_id}"),
                "description": "The provenance events and artifacts of one agent-state run, exported for review. It is not signed and makes no claim of scientific validity.",
                "datePublished": exported_at,
                "license": {"@id": "#usage"},
                "conformsTo": {"@id": PROCESS_RUN_CRATE},
                "hasPart": artifact_entities.iter().map(|entity| json!({"@id": entity["@id"]})).collect::<Vec<_>>(),
                "mentions": mentions
            }),
            json!({
                "@id": PROCESS_RUN_CRATE,
                "@type": "CreativeWork",
                "name": "Process Run Crate",
                "version": "0.6"
            }),
            action,
            json!({
                "@id": "#usage",
                "@type": "CreativeWork",
                "name": "No license granted",
                "description": "No license is granted by this export. Use follows the owning project's data agreement."
            }),
            json!({
                "@id": "#runtime",
                "@type": "SoftwareApplication",
                "name": env!("CARGO_PKG_NAME"),
                "description": "The agent-state runtime that recorded the run. The run record keeps no runtime version."
            }),
            json!({
                "@id": "#profile",
                "@type": "CreativeWork",
                "name": run.profile,
                "description": "The state-view profile the run was recorded under: what of the run's state an agent is shown, and how much it keeps."
            }),
            json!({
                "@id": "#export",
                "@type": "CreateAction",
                "name": format!("Export of run {run_id}"),
                "instrument": {"@id": "#exporter"},
                "object": {"@id": action_id},
                "result": {"@id": "./"},
                "endTime": exported_at
            }),
            json!({
                "@id": "#exporter",
                "@type": "SoftwareApplication",
                "name": env!("CARGO_PKG_NAME"),
                "softwareVersion": env!("CARGO_PKG_VERSION")
            }),
            json!({
                "@id": format!("#agent-{}", run.subject),
                "@type": ["SoftwareApplication", "prov:Agent"],
                "name": run.subject
            }),
        ];
        graph.extend(event_nodes.clone());
        graph.extend(artifact_entities.clone());
        graph.extend(term_definitions());
        write_private(
            &pending.join("ro-crate-metadata.json"),
            &serde_json::to_vec_pretty(&json!({
                "@context": export_context(),
                "@graph": graph
            }))?,
        )?;
        write_private(
            &pending.join("provenance.json"),
            &serde_json::to_vec_pretty(&json!({
                "schema_version": 1,
                "run": run,
                "events": event_nodes,
                "artifacts": artifact_entities,
                "event_payloads_included": include_event_payloads,
                "restricted_artifacts_included": include_restricted
            }))?,
        )?;
        let manifest = build_export_manifest(&pending)?;
        write_private(&pending.join("manifest-sha256.txt"), manifest.as_bytes())?;
        let manifest_sha256 = hash_bytes(manifest.as_bytes());
        Ok((
            events.len(),
            artifact_links.len(),
            copied.len(),
            omitted.len(),
            manifest_sha256,
        ))
    })();
    let (events, artifact_links, copied_artifacts, restricted_artifacts_omitted, manifest_sha256) =
        match result {
            Ok(value) => value,
            Err(error) => {
                let _ = fs::remove_dir_all(&pending);
                return Err(error);
            }
        };
    fs::rename(&pending, output_dir)?;
    audit::append(
        config,
        "host-controller",
        "agent-state.export",
        &format!("agent-state/{run_id}"),
        "passed",
        json!({
            "events": events,
            "artifact_links": artifact_links,
            "copied_artifacts": copied_artifacts,
            "restricted_artifacts_omitted": restricted_artifacts_omitted,
            "event_payloads_included": include_event_payloads,
            "manifest_sha256": manifest_sha256
        }),
    )?;
    Ok(StateExportReceipt {
        run_id: run_id.into(),
        output_dir: output_dir.into(),
        events,
        artifact_links,
        copied_artifacts,
        restricted_artifacts_omitted,
        event_payloads_included: include_event_payloads,
        manifest_sha256,
    })
}

pub(super) fn artifacts_for_run(
    config: &RuntimeConfig,
    run_id: &str,
) -> Result<Vec<RunArtifactLink>> {
    let connection = open_database(config)?;
    let mut statement = connection.prepare(
        "SELECT l.event_id, a.sha256, a.size, l.media_type, l.role, l.label, l.sensitivity, a.relative_path, a.created_at
         FROM artifact_links l
         JOIN artifacts a ON a.sha256 = l.sha256
         JOIN state_events e ON e.event_id = l.event_id
         WHERE e.run_id = ?1
         ORDER BY e.sequence, l.sha256, l.role",
    )?;
    let rows = statement.query_map(params![run_id], |row| {
        let sensitivity = row.get::<_, String>(6)?;
        Ok((
            row.get::<_, String>(0)?,
            ArtifactRecord {
                schema_version: 1,
                sha256: row.get(1)?,
                size: row.get(2)?,
                media_type: row.get(3)?,
                role: row.get(4)?,
                label: row.get(5)?,
                sensitivity: parse_artifact_sensitivity(&sensitivity)
                    .map_err(|_| rusqlite::Error::InvalidQuery)?,
                relative_path: row.get(7)?,
                created_at: row.get(8)?,
            },
        ))
    })?;
    rows.map(|row| {
        let (event_id, artifact) = row?;
        Ok(RunArtifactLink { event_id, artifact })
    })
    .collect()
}

pub fn read_artifact_bounded(
    config: &RuntimeConfig,
    run_id: &str,
    sha256: &str,
    max_bytes: u64,
) -> Result<(ArtifactRecord, Vec<u8>)> {
    validate_identifier(run_id, "run id")?;
    if sha256.len() != 64 || !sha256.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        bail!("artifact digest must be SHA-256");
    }
    if max_bytes == 0 || max_bytes > 256 * 1024 * 1024 {
        bail!("browser artifact reads must be between one byte and 256 MiB");
    }
    let link = artifacts_for_run(config, run_id)?
        .into_iter()
        .find(|link| link.artifact.sha256 == sha256)
        .context("artifact is not linked to this run")?;
    if link.artifact.size > max_bytes {
        bail!("artifact exceeds the browser evidence limit; export the run package instead");
    }
    let path = config
        .agent_state_artifacts_dir()
        .join(&link.artifact.relative_path);
    let metadata = fs::symlink_metadata(&path)?;
    if metadata.file_type().is_symlink()
        || !metadata.is_file()
        || metadata.len() != link.artifact.size
    {
        bail!("artifact custody record does not match stored bytes");
    }
    let bytes = fs::read(&path)?;
    if hash_bytes(&bytes) != link.artifact.sha256 {
        bail!("artifact digest verification failed");
    }
    Ok((link.artifact, bytes))
}

pub(super) fn build_export_manifest(root: &Path) -> Result<String> {
    let mut paths = WalkDir::new(root)
        .follow_links(false)
        .into_iter()
        .collect::<std::result::Result<Vec<_>, _>>()?
        .into_iter()
        .filter(|entry| entry.file_type().is_file())
        .map(|entry| entry.into_path())
        .collect::<Vec<_>>();
    paths.sort();
    let mut manifest = String::new();
    for path in paths {
        let relative = path
            .strip_prefix(root)?
            .to_str()
            .context("export path is not valid UTF-8")?
            .replace('\\', "/");
        let (sha256, _) = hash_file(&path)?;
        manifest.push_str(&sha256);
        manifest.push_str("  ");
        manifest.push_str(&relative);
        manifest.push('\n');
    }
    Ok(manifest)
}
