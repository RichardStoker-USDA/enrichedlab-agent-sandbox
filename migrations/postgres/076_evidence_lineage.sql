-- The research record's lineage graph: stable identities for agents, activities and
-- entities, and immutable edges between them, written by evidence.append from the `lineage` block of a record's payload
-- in the same transaction as the record. The record's hash covers the payload bytes, so the chain covers the lineage.
--
-- Shapes follow W3C PROV: an activity used entities and generated entities, an entity was derived from another, an
-- activity was associated with an agent in a role, and an activity was informed by another only where the producer
-- states that one's result caused the other. An entity's content digest is an attribute, not its identity. Every edge
-- names the record that asserted it and is tenant-qualified at both ends.
--
-- Lineage payload, version 1 (all members optional except version; unknown members are refused):
--   {"lineage": {"version": 1,
--     "activity": {"key", "kind", "event": started|ended|failed|cancelled, "at"},
--     "agents": [{"kind", "identity", "version", "image_digest", "role"}],
--     "entities": [{"key", "kind", "sha256", "size", "media_type", "uri", "object_version", "disclosure", "origin"}],
--     "used": [{"entity", "role"}], "generated": [{"entity", "role"}],
--     "derived": [{"from", "to", "transform"}], "informed_by": ["activity key"],
--     "model_call": {"agent", "decoding", "prompt_sha256", "completion_sha256", "tool_calls_sha256",
--                    "reasoning_sha256", "input_tokens", "output_tokens", "latency_ms", "cache"}}}
-- Keys name activities within the record's stream and entities within its lab and project. An entity is generated by at
-- most one activity, declared in the same record. An activity belongs to the producer that registered it. Only broker
-- producers may name a person agent or a review activity. Reads go through evidence.trace_activity, with the same
-- person, disclosure and purpose decision as evidence.verify_stream (075).
--
-- Rollback: an earlier coordinator reads none of this; evidence.append from 075 is replaced, so rolling back means
-- restoring 075's function body (kept in the migration file).
BEGIN;

CREATE TABLE IF NOT EXISTS evidence.agents (
  tenant_id text NOT NULL,
  agent_id uuid NOT NULL DEFAULT uuidv7(),
  kind text NOT NULL CHECK (kind IN ('person', 'model', 'tool', 'service', 'sandbox')),
  identity text NOT NULL CHECK (length(identity) BETWEEN 1 AND 256 AND identity ~ '\S' AND identity !~ '[[:cntrl:]]'),
  version text CHECK (version IS NULL OR (length(version) BETWEEN 1 AND 128 AND version ~ '\S'
    AND version !~ '[[:cntrl:]]')),
  image_digest text CHECK (image_digest IS NULL OR image_digest ~ '^sha256:[0-9a-f]{64}$'),
  first_record uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (tenant_id, agent_id),
  UNIQUE NULLS NOT DISTINCT (tenant_id, kind, identity, version, image_digest),
  CHECK (kind <> 'model' OR version IS NOT NULL OR image_digest IS NOT NULL),
  CHECK (kind <> 'tool' OR (version IS NOT NULL AND image_digest IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS evidence.activities (
  tenant_id text NOT NULL,
  activity_id uuid NOT NULL DEFAULT uuidv7(),
  stream_id uuid NOT NULL,
  activity_key text NOT NULL CHECK (activity_key ~ '^[A-Za-z0-9._:/-]{1,128}$'),
  kind text NOT NULL CHECK (kind IN ('step', 'model_call', 'query', 'analysis', 'tool', 'export', 'review', 'ingest',
    'sandbox_run')),
  producer_id uuid NOT NULL,
  first_record uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (tenant_id, activity_id),
  UNIQUE (tenant_id, stream_id, activity_key),
  FOREIGN KEY (tenant_id, stream_id) REFERENCES evidence.streams (tenant_id, stream_id),
  FOREIGN KEY (tenant_id, producer_id) REFERENCES evidence.producers (tenant_id, producer_id)
);

CREATE TABLE IF NOT EXISTS evidence.entities (
  tenant_id text NOT NULL,
  entity_id uuid NOT NULL DEFAULT uuidv7(),
  group_key text NOT NULL,
  project_id uuid,
  entity_key text NOT NULL CHECK (entity_key ~ '^[A-Za-z0-9._:/-]{1,160}$'),
  kind text NOT NULL CHECK (kind IN ('artifact', 'dataset', 'query_result', 'code', 'model_text', 'figure', 'paper',
    'document', 'environment', 'image', 'parameters', 'other')),
  content_sha256 text CHECK (content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes bigint CHECK (size_bytes IS NULL OR size_bytes >= 0),
  media_type text CHECK (media_type IS NULL OR media_type ~ '^[a-z0-9.+-]+/[A-Za-z0-9.+-]+$'),
  object_uri text CHECK (object_uri IS NULL OR (length(object_uri) <= 1024 AND object_uri !~ '[\s]')),
  object_version text CHECK (object_version IS NULL OR length(object_version) <= 256),
  disclosure text NOT NULL CHECK (disclosure IN ('restricted', 'project', 'lab', 'public')),
  origin text NOT NULL CHECK (origin IN ('produced', 'imported', 'external')),
  generated_by uuid,
  first_record uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (tenant_id, entity_id),
  UNIQUE NULLS NOT DISTINCT (tenant_id, group_key, project_id, entity_key),
  FOREIGN KEY (tenant_id, group_key) REFERENCES enrichedlab_agent.broker_research_groups (tenant_id, group_key),
  FOREIGN KEY (tenant_id, project_id) REFERENCES enrichedlab_agent.broker_projects (tenant_id, project_id),
  FOREIGN KEY (tenant_id, generated_by) REFERENCES evidence.activities (tenant_id, activity_id),
  CHECK ((origin = 'produced') = (generated_by IS NOT NULL))
);

