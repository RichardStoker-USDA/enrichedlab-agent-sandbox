-- One activity's provenance for the signed-in person, for a purpose: its events, its agents in their roles, the
-- entities it used (each with the activity that generated it, when known), the entities it generated with their
-- derivations, and the activities that informed it. Every element names the record and producer that asserted it.
-- Restricted entities appear only at the restricted scope; otherwise each is listed as withheld, without key, digest
-- or size. Each section holds at most 200 elements in a fixed order (and each derivation list 50); a longer one is cut
-- and named in "truncated". Metadata only: never an object location or a payload. The read is recorded.
CREATE OR REPLACE FUNCTION evidence.trace_activity(p_tenant text, p_actor uuid, p_stream uuid, p_activity_key text,
  p_purpose text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, evidence, enrichedlab_agent
SET enrichedlab.tenant_id = '' AS $$
DECLARE
  head evidence.streams%ROWTYPE;
  act evidence.activities%ROWTYPE;
  scope text;
  cap constant integer := 200;
  derived_cap constant integer := 50;
  sections jsonb;
  truncated text[] := '{}';
  section text;
BEGIN
  IF p_purpose IS NULL OR p_purpose NOT IN ('review', 'reproduce', 'audit') THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'evidence:purpose_invalid';
  END IF;
  PERFORM set_config('enrichedlab.tenant_id', p_tenant, true);
  SELECT * INTO head FROM evidence.streams WHERE tenant_id = p_tenant AND stream_id = p_stream;
  IF FOUND THEN
    scope := evidence.read_scope(p_tenant, p_actor, head.group_key, head.project_id, p_purpose);
  END IF;
  IF scope IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'evidence:stream_unknown';
  END IF;
  SELECT * INTO act FROM evidence.activities
    WHERE tenant_id = p_tenant AND stream_id = p_stream AND activity_key = p_activity_key;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'evidence:activity_unknown'; END IF;
  INSERT INTO evidence.reads (tenant_id, actor_id, stream_id, reader, activity_key, purpose, scope)
    VALUES (p_tenant, p_actor, p_stream, 'trace_activity', p_activity_key, p_purpose, scope);

  sections := jsonb_build_object(
    'events', (SELECT coalesce(jsonb_agg(z.v ORDER BY z.n), '[]') FROM (
      SELECT row_number() OVER (ORDER BY e.occurred_at, e.record_id) AS n,
        jsonb_build_object('event', e.event, 'at', evidence.utc_text(e.occurred_at), 'record', e.record_id,
          'producer', p.identity) AS v
      FROM evidence.activity_events e
      JOIN evidence.receipts rc ON rc.tenant_id = e.tenant_id AND rc.record_id = e.record_id
      JOIN evidence.producers p ON p.tenant_id = rc.tenant_id AND p.producer_id = rc.producer_id
      WHERE e.tenant_id = p_tenant AND e.activity_id = act.activity_id
      ORDER BY e.occurred_at, e.record_id LIMIT cap + 1) z),
    'agents', (SELECT coalesce(jsonb_agg(z.v ORDER BY z.n), '[]') FROM (
      SELECT row_number() OVER (ORDER BY x.ingested_at, x.record_id, a.agent_id, x.role) AS n,
        jsonb_build_object('kind', a.kind, 'identity', a.identity, 'version', a.version, 'image_digest', a.image_digest,
          'role', x.role, 'record', x.record_id, 'producer', p.identity) AS v
      FROM evidence.associated x
      JOIN evidence.agents a ON a.tenant_id = x.tenant_id AND a.agent_id = x.agent_id
      JOIN evidence.receipts rc ON rc.tenant_id = x.tenant_id AND rc.record_id = x.record_id
      JOIN evidence.producers p ON p.tenant_id = rc.tenant_id AND p.producer_id = rc.producer_id
      WHERE x.tenant_id = p_tenant AND x.activity_id = act.activity_id
      ORDER BY x.ingested_at, x.record_id, a.agent_id, x.role LIMIT cap + 1) z),
    'used', (SELECT coalesce(jsonb_agg(z.v ORDER BY z.n), '[]') FROM (
      SELECT row_number() OVER (ORDER BY u.ingested_at, u.record_id, e.entity_id, u.role) AS n,
        CASE WHEN e.disclosure = 'restricted' AND scope <> 'restricted' THEN
          jsonb_build_object('withheld', true, 'disclosure', e.disclosure, 'role', u.role, 'record', u.record_id,
            'producer', p.identity)
        ELSE jsonb_build_object('entity', e.entity_key, 'kind', e.kind, 'sha256', e.content_sha256,
          'size', e.size_bytes, 'disclosure', e.disclosure, 'origin', e.origin, 'role', u.role,
          'generated_by', ga.activity_key, 'generated_in_stream', ga.stream_id, 'record', u.record_id,
          'producer', p.identity) END AS v
      FROM evidence.used u
      JOIN evidence.entities e ON e.tenant_id = u.tenant_id AND e.entity_id = u.entity_id
      LEFT JOIN evidence.activities ga ON ga.tenant_id = e.tenant_id AND ga.activity_id = e.generated_by
      JOIN evidence.receipts rc ON rc.tenant_id = u.tenant_id AND rc.record_id = u.record_id
      JOIN evidence.producers p ON p.tenant_id = rc.tenant_id AND p.producer_id = rc.producer_id
      WHERE u.tenant_id = p_tenant AND u.activity_id = act.activity_id
      ORDER BY u.ingested_at, u.record_id, e.entity_id, u.role LIMIT cap + 1) z),
    'generated', (SELECT coalesce(jsonb_agg(z.v ORDER BY z.n), '[]') FROM (
      SELECT row_number() OVER (ORDER BY g.ingested_at, g.record_id, e.entity_id) AS n,
        CASE WHEN e.disclosure = 'restricted' AND scope <> 'restricted' THEN
          jsonb_build_object('withheld', true, 'disclosure', e.disclosure, 'role', g.role, 'record', g.record_id,
            'producer', p.identity)
        ELSE jsonb_build_object('entity', e.entity_key, 'kind', e.kind, 'sha256', e.content_sha256,
          'size', e.size_bytes, 'disclosure', e.disclosure, 'role', g.role, 'record', g.record_id,
          'producer', p.identity,
          'derived_from', (SELECT coalesce(jsonb_agg(d2.v ORDER BY d2.n), '[]') FROM (
            SELECT row_number() OVER (ORDER BY d.ingested_at, d.record_id, f.entity_id) AS n,
              CASE WHEN f.disclosure = 'restricted' AND scope <> 'restricted' THEN
                jsonb_build_object('withheld', true, 'disclosure', f.disclosure, 'transform', d.transform,
                  'record', d.record_id, 'producer', dp.identity)
              ELSE jsonb_build_object('entity', f.entity_key, 'transform', d.transform, 'record', d.record_id,
                'producer', dp.identity) END AS v
            FROM evidence.derived d
            JOIN evidence.entities f ON f.tenant_id = d.tenant_id AND f.entity_id = d.from_entity
            JOIN evidence.receipts drc ON drc.tenant_id = d.tenant_id AND drc.record_id = d.record_id
            JOIN evidence.producers dp ON dp.tenant_id = drc.tenant_id AND dp.producer_id = drc.producer_id
            WHERE d.tenant_id = p_tenant AND d.to_entity = e.entity_id
            ORDER BY d.ingested_at, d.record_id, f.entity_id LIMIT derived_cap) d2),
          'derived_from_truncated', (SELECT count(*) > derived_cap FROM (SELECT 1 FROM evidence.derived d
            WHERE d.tenant_id = p_tenant AND d.to_entity = e.entity_id LIMIT derived_cap + 1) c)) END AS v
      FROM evidence.generated g
      JOIN evidence.entities e ON e.tenant_id = g.tenant_id AND e.entity_id = g.entity_id
      JOIN evidence.receipts rc ON rc.tenant_id = g.tenant_id AND rc.record_id = g.record_id
      JOIN evidence.producers p ON p.tenant_id = rc.tenant_id AND p.producer_id = rc.producer_id
      WHERE g.tenant_id = p_tenant AND g.activity_id = act.activity_id
      ORDER BY g.ingested_at, g.record_id, e.entity_id LIMIT cap + 1) z),
    'informed_by', (SELECT coalesce(jsonb_agg(z.v ORDER BY z.n), '[]') FROM (
      SELECT row_number() OVER (ORDER BY i.ingested_at, i.record_id, i2.activity_id) AS n,
        jsonb_build_object('activity', i2.activity_key, 'record', i.record_id, 'producer', p.identity) AS v
      FROM evidence.informed i
      JOIN evidence.activities i2 ON i2.tenant_id = i.tenant_id AND i2.activity_id = i.informant_id
      JOIN evidence.receipts rc ON rc.tenant_id = i.tenant_id AND rc.record_id = i.record_id
      JOIN evidence.producers p ON p.tenant_id = rc.tenant_id AND p.producer_id = rc.producer_id
      WHERE i.tenant_id = p_tenant AND i.activity_id = act.activity_id
      ORDER BY i.ingested_at, i.record_id, i2.activity_id LIMIT cap + 1) z));
  FOREACH section IN ARRAY ARRAY['events', 'agents', 'used', 'generated', 'informed_by'] LOOP
    IF jsonb_array_length(sections->section) > cap THEN
      truncated := truncated || section;
      sections := jsonb_set(sections, ARRAY[section], (sections->section) - cap);
    END IF;
  END LOOP;
  RETURN jsonb_build_object(
    'activity', jsonb_build_object('key', act.activity_key, 'kind', act.kind, 'first_record', act.first_record,
      'registered_by', (SELECT p.identity FROM evidence.producers p
        WHERE p.tenant_id = p_tenant AND p.producer_id = act.producer_id)),
    'scope', scope, 'truncated', to_jsonb(truncated)) || sections;
END;
$$;
