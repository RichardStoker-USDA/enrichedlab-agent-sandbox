  completion_sha256 text NOT NULL CHECK (completion_sha256 ~ '^[0-9a-f]{64}$'),
  tool_calls_sha256 text CHECK (tool_calls_sha256 IS NULL OR tool_calls_sha256 ~ '^[0-9a-f]{64}$'),
